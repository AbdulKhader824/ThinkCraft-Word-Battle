  static List<String> forLevel(WordLevel level) => switch (level) {
    WordLevel.easy => easy,
    WordLevel.medium => medium,
    WordLevel.hard => hard,
    WordLevel.mixed => [...easy, ...medium, ...hard],
  };

  /// [count] different words at [level], skipping those in [used] while
  /// enough are left.
  static List<String> pick(
    WordLevel level,
    Random random, {
    Set<String> used = const {},
    int count = 3,
  }) {
    final all = forLevel(level);
    var fresh = all.where((word) => !used.contains(word)).toList();
    // Every word has been drawn: start the list again.
    if (fresh.length < count) fresh = [...all];
    fresh.shuffle(random);
    return fresh.take(count).toList();
  }
