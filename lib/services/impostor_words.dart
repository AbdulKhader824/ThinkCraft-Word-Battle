  static List<String> forTopic(ImpostorTopic topic) => byTopic[topic]!;

  /// Picks a topic from [topics] and a word in it that isn't in [used],
  /// with [ImpostorRules.guessChoiceCount] words from the same topic for
  /// the Impostor's guess, the real one among them, shuffled.
  ///
  /// Once a topic's words are all used, it starts again.
  static ({ImpostorTopic topic, String word, List<String> choices}) pick(
    Set<ImpostorTopic> topics,
    Random random, {
    Set<String> used = const {},
    int choiceCount = ImpostorRules.guessChoiceCount,
  }) {
    final open = [
      for (final topic in ImpostorTopic.values)
        if (topics.contains(topic) &&
            forTopic(topic).any((word) => !used.contains(word)))
          topic,
    ];
    final topicList = open.isNotEmpty
        ? open
        : [
            for (final topic in ImpostorTopic.values)
              if (topics.contains(topic)) topic,
          ];
    final topic = topicList[random.nextInt(topicList.length)];
    final words = forTopic(topic);
    final fresh = [
      for (final word in words)
        if (!used.contains(word)) word,
    ];
    final pool = fresh.isEmpty ? words : fresh;
    final word = pool[random.nextInt(pool.length)];
    final others = [
      for (final other in words)
        if (other != word) other,
    ]..shuffle(random);
    final choices = [word, ...others.take(choiceCount - 1)]..shuffle(random);
    return (topic: topic, word: word, choices: choices);
  }
