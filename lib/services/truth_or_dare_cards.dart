  /// The cards of [kind] for [level]. Mix uses Kids and Teens together.
  static List<String> deck(TodLevel level, TodKind kind) => switch (level) {
    TodLevel.mix => [
      ...decks[TodLevel.kids]![kind]!,
      ...decks[TodLevel.teens]![kind]!,
    ],
    _ => decks[level]![kind]!,
  };

  /// Picks a card of [kind] for [level] that isn't in [used]. Once every
  /// card has been played, any card can come up again.
  static String pick(
    TodLevel level,
    TodKind kind,
    Set<String> used,
    Random random,
  ) {
    final all = deck(level, kind);
    final fresh = [
      for (final card in all)
        if (!used.contains(card)) card,
    ];
    final pool = fresh.isEmpty ? all : fresh;
    return pool[random.nextInt(pool.length)];
  }
