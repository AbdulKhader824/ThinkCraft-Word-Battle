  static List<String> forTopic(MostLikelyTopic topic) => byTopic[topic]!;

  /// Picks a topic from [topics] and a question in it that isn't in
  /// [used]. Once a topic's questions are all used, it starts again.
  static ({MostLikelyTopic topic, String question}) pick(
    Set<MostLikelyTopic> topics,
    Random random, {
    Set<String> used = const {},
  }) {
    final chosen = [
      for (final topic in MostLikelyTopic.values)
        if (topics.contains(topic)) topic,
    ];
    final open = [
      for (final topic in chosen)
        if (forTopic(topic).any((question) => !used.contains(question))) topic,
    ];
    final topicList = open.isNotEmpty ? open : chosen;
    final topic = topicList[random.nextInt(topicList.length)];
    final questions = forTopic(topic);
    final fresh = [
      for (final question in questions)
        if (!used.contains(question)) question,
    ];
    final pool = fresh.isEmpty ? questions : fresh;
    return (topic: topic, question: pool[random.nextInt(pool.length)]);
  }
